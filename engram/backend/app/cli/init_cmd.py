"""`engram init` — write-time 环境推断，生成显式 `.env`。

行为契约（openspec change simplify-configuration）：
- 探测宿主机环境（Docker/PG/Redis/Node/前端产物），把结论写成显式键值；
  运行时只读这些值，不做任何感知或推断。
- 只问 2 把密钥（LLM、Tavily 可选）+ 2 个授权问题（MCP、沙箱）。
- 权力授予类功能（MCP、沙箱）默认关闭：依赖齐备也绝不自动开启。
- 只读类功能（记忆、Skill、Web）由 init 依探测结论自动写入启用键。
- 已有 `.env` 默认不重写；`--force` 才重新生成（先备份为 `.env.bak`）。
"""
from __future__ import annotations

import datetime as _dt
import shutil
from pathlib import Path
from typing import Callable, Mapping

from rich.console import Console
from rich.panel import Panel
from rich.table import Table
from rich.text import Text

from engram.backend.app.cli.probes import ProbeResult, probe_all

LOCAL_SANDBOX = (
    "engram.backend.agents.sandbox.local.local_sandbox_provider:LocalSandboxProvider"
)
DOCKER_SANDBOX = (
    "engram.backend.agents.sandbox.docker.docker_sandbox_provider:DockerSandboxProvider"
)

InFn = Callable[[str], str]


def _ask_yes_no(input_fn: InFn, prompt: str, default: bool = False) -> bool:
    hint = "Y/n" if default else "y/N"
    raw = input_fn(f"{prompt} ({hint}): ").strip().lower()
    if not raw:
        return default
    return raw in ("y", "yes", "是")


def _ask_provider(input_fn: InFn, console: Console) -> tuple[str, str]:
    """问 LLM provider + API Key（返回 provider 名与 key；key 可空）。"""
    from engram.backend.agents.config.provider_profile import PROVIDER_PROFILES

    selectable = [p for p in PROVIDER_PROFILES if p.name != "fake"]
    default = next((p for p in selectable if p.is_default), selectable[0])
    console.print("\n[bold]LLM Provider[/bold]（密钥稍后可改，其他 provider 见 docs/configuration.md）")
    for i, profile in enumerate(selectable, 1):
        default_tag = " [dim](默认)[/dim]" if profile is default else ""
        console.print(f"  [{i}] [cyan]{profile.name}[/cyan]{default_tag} — {profile.default_model}")

    raw = input_fn(f"选择 provider 编号（回车={default.name}）: ").strip()
    profile = default
    if raw:
        try:
            profile = selectable[int(raw) - 1]
        except (ValueError, IndexError):
            console.print(f"[yellow]无效编号，使用默认 {default.name}。[/yellow]")
    key = input_fn(f"{profile.name} API Key（回车跳过）: ").strip()
    return profile.name, key


def _ask_sandbox(
    input_fn: InFn,
    console: Console,
    probes: Mapping[str, ProbeResult],
) -> str:
    """授权沙箱并选择模式；返回 provider 路径或空串。"""
    if not _ask_yes_no(
        input_fn,
        "启用沙箱（权力授予：允许在宿主机/容器执行命令）？",
        default=False,
    ):
        return ""
    docker_ok = bool(probes.get("docker") and probes["docker"].available)
    node_ok = bool(probes.get("node") and probes["node"].available)
    if docker_ok:
        console.print("  [1] Local — 宿主机进程（无隔离）")
        console.print("  [2] Docker — 容器隔离（推荐）")
        choice = input_fn("选择沙箱模式（回车=Docker）: ").strip()
        if choice == "1":
            return LOCAL_SANDBOX
        return DOCKER_SANDBOX
    console.print("[yellow]未探测到 Docker daemon，只能使用 Local 沙箱（宿主机 bash，无隔离）。[/yellow]")
    if not node_ok:
        console.print("[yellow]警告：未探测到 Node.js，沙箱内 npm 类工具可能不可用。[/yellow]")
    if _ask_yes_no(input_fn, "仍要启用 Local 沙箱？", default=False):
        return LOCAL_SANDBOX
    return ""


def render_env(
    *,
    provider: str,
    api_key: str,
    tavily_key: str,
    mcp: bool,
    sandbox_path: str,
    probes: Mapping[str, ProbeResult],
    generated_on: str,
) -> str:
    """把交互答案 + 探测结论渲染成显式 `.env` 文本。"""
    phase2 = bool(
        probes.get("pg") and probes["pg"].available
        and probes.get("redis") and probes["redis"].available
    )
    web_ui = bool(probes.get("web_dist") and probes["web_dist"].available)
    key_name = f"{provider.upper()}_API_KEY"

    lines: list[str] = [
        f"# Engram .env — generated by `engram init` on {generated_on}.",
        "# Full variable reference: docs/configuration.md",
        "# Secrets are plain text; .env is gitignored. Re-run with --force to regenerate.",
        "",
        "# LLM（至少一个 provider 密钥）",
        f"{key_name}={api_key}",
        "",
        "# Tavily 联网搜索（可选；留空回退 DuckDuckGo）",
        f"TAVILY_API_KEY={tavily_key}" if tavily_key else "# TAVILY_API_KEY=",
        "",
        "# 权力授予开关（只有明确同意才开启）",
        f"ENGRAM_MCP_ENABLED={'true' if mcp else 'false'}",
        f"ENGRAM_SANDBOX_USE={sandbox_path}",
    ]
    if sandbox_path == LOCAL_SANDBOX:
        lines.append("ENGRAM_SANDBOX_ALLOW_HOST_BASH=true")
    lines += [
        "",
        "# 探测结论（显式写入；运行时只读这些值，不再探测）",
        "ENGRAM_MEMORY_USE=default",
        f"ENGRAM_MEMORY_PHASE2_ENABLED={'true' if phase2 else 'false'}",
        "ENGRAM_SKILL_ENABLED=true",
        f"ENGRAM_WEB_UI_ENABLED={'true' if web_ui else 'false'}",
        "ENGRAM_MULTIAGENT_ENABLED=true",
        "",
        "# ---- 探测详情（注释，仅供人工核对）----",
    ]
    for name in ("docker", "pg", "redis", "node", "web_dist", "mcp_config", "llm", "tavily"):
        result = probes.get(name)
        if result is None:
            continue
        mark = "可用" if result.available else "不可用"
        lines.append(f"# {name}: {mark} — {result.detail}")
    lines.append("# Docker compose 部署会注入 DSN（checkpoint/Redis/memory PG），无需写进本文件。")
    lines.append("")
    return "\n".join(lines)


def _print_probe_table(console: Console, probes: Mapping[str, ProbeResult]) -> None:
    table = Table(title="环境探测", show_lines=False)
    table.add_column("探测项", style="cyan")
    table.add_column("结果")
    table.add_column("说明")
    for name in ("docker", "pg", "redis", "node", "web_dist", "mcp_config", "llm", "tavily"):
        result = probes.get(name)
        if result is None:
            continue
        state = "[green]可用[/green]" if result.available else "[yellow]不可用[/yellow]"
        table.add_row(name, state, result.detail)
    console.print(table)


def run_init(
    project_root: Path,
    *,
    force: bool = False,
    input_fn: InFn = input,
    console: Console | None = None,
    probes: Mapping[str, ProbeResult] | None = None,
    generated_on: str | None = None,
) -> int:
    """`engram init` 主流程。返回进程退出码。"""
    console = console or Console()
    env_path = Path(project_root) / ".env"

    if env_path.exists() and not force:
        console.print(
            "[yellow].env 已存在，未做任何修改。[/yellow]\n"
            "[dim]重新生成请运行 engram init --force（原文件备份为 .env.bak）。[/dim]"
        )
        return 0

    probe_results = probes if probes is not None else probe_all(Path(project_root))

    console.print(Panel(
        Text("Engram init\n", justify="center", style="bold cyan")
        + Text("探测本机环境，只问密钥与授权；结论写成显式 .env。", justify="center", style="dim")
        + Text("按 Ctrl+C 可随时取消。", justify="center", style="dim"),
        border_style="cyan",
    ))
    _print_probe_table(console, probe_results)

    try:
        provider, api_key = _ask_provider(input_fn, console)
        if not api_key:
            console.print("[yellow]未填写 LLM 密钥；稍后需手动补进 .env，否则无法对话。[/yellow]")
        tavily_key = input_fn("Tavily API Key（可选，回车跳过）: ").strip()

        console.print("\n[bold]授权[/bold]（默认关闭；依赖齐备也不会自动开启）")
        mcp = _ask_yes_no(
            input_fn,
            "启用 MCP 工具（权力授予：可执行任意 npm 包代码）？",
            default=False,
        )
        if mcp and not (probe_results.get("mcp_config") and probe_results["mcp_config"].available):
            console.print(
                "[yellow]MCP 配置文件缺失；doctor 会将 MCP 标记为 broken，"
                "直到你创建 .engram/mcp_servers.yaml。[/yellow]"
            )
        sandbox_path = _ask_sandbox(input_fn, console, probe_results)
    except (KeyboardInterrupt, EOFError):
        console.print("\n[yellow]已取消，未写入 .env。[/yellow]")
        return 1

    content = render_env(
        provider=provider,
        api_key=api_key,
        tavily_key=tavily_key,
        mcp=mcp,
        sandbox_path=sandbox_path,
        probes=probe_results,
        generated_on=generated_on or _dt.date.today().isoformat(),
    )

    if env_path.exists():
        backup = env_path.with_name(".env.bak")
        shutil.copy2(env_path, backup)
        console.print(f"[dim]原 .env 已备份到 {backup.name}[/dim]")
    env_path.write_text(content, encoding="utf-8")

    console.print(f"\n[green]✓ 已生成 {env_path}[/green]")
    if probe_results.get("docker") and probe_results["docker"].available:
        console.print("[bold]下一步:[/bold] docker compose up -d && engram doctor")
    else:
        console.print(
            "[bold]未探测到 Docker：[/bold]本地轻量形态（Markdown 记忆，无 PG 会话持久化）。\n"
            "直接运行 `engram` 开始；体检用 `engram doctor`。"
        )
    return 0